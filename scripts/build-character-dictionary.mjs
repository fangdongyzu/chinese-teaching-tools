import fs from "node:fs/promises";
import { createHash } from "node:crypto";

// Original CVDICT, retained by a public fork. Pin the revision for reproducibility.
const revision = "c379d909e308343a247e51619f7839a2060a271c";
const source = `https://raw.githubusercontent.com/kemonra/CVDICT/${revision}/CVDICT.u8`;
const text = process.argv[2]
  ? await fs.readFile(process.argv[2], "utf8")
  : await fetch(source).then((r) => {
      if (!r.ok) throw new Error("Dictionary download failed.");
      return r.text();
    });
const characters = new Map();
for (const line of text.split(/\r?\n/)) {
  const match = line.match(/^(\S+) (\S+) \[([^\]]+)\] \/(.*)\/$/);
  if (!match || [...match[1]].length !== 1 || [...match[2]].length !== 1)
    continue;
  const [, traditional, simplified, pinyin, definition] = match;
  for (const char of new Set([traditional, simplified])) {
    if (!/\p{Script=Han}/u.test(char)) continue;
    const entries = characters.get(char) || [];
    entries.push({
      pinyin,
      meanings: definition.split("/").filter(Boolean),
      direct: traditional === char,
    });
    characters.set(char, entries);
  }
}
const shards = Array.from({ length: 64 }, () => ({}));
for (const [char, entries] of characters) {
  // Prefer ordinary readings over proper names, and exact traditional forms
  // over definitions reached through simplified-character aliases.
  entries.sort(
    (a, b) =>
      Number(/^[A-Z]/.test(a.pinyin)) - Number(/^[A-Z]/.test(b.pinyin)) ||
      Number(b.direct) - Number(a.direct),
  );
  const readings = new Map();
  for (const entry of entries) {
    const key = entry.pinyin.toLowerCase();
    const meanings = readings.get(key) || [];
    for (const meaning of entry.meanings)
      if (!meanings.includes(meaning)) meanings.push(meaning);
    readings.set(key, meanings);
  }
  shards[char.codePointAt(0) % 64][char] = [...readings].map(
    ([pinyin, meanings]) => ({ pinyin, meanings }),
  );
}
const dir = new URL("../public/data/character-dictionary/", import.meta.url);
await fs.mkdir(dir, { recursive: true });
await Promise.all(
  shards.map((shard, i) =>
    fs.writeFile(new URL(`${i}.json`, dir), JSON.stringify(shard) + "\n"),
  ),
);
await fs.writeFile(
  new URL("NOTICE.txt", dir),
  `Chinese-Vietnamese character dictionary\n\nAuthor: Phong Phan and CC-CEDICT contributors.\nOriginal: https://github.com/ph0ngp/CVDICT\nSnapshot: ${source}\nSHA-256: ${createHash("sha256").update(text).digest("hex")}\n\nChanges: extracted single-character entries, indexed both traditional and simplified forms, grouped readings and meanings, split into 64 files.\n${characters.size} characters. Generated by scripts/build-character-dictionary.mjs.\n\nThis derived dictionary is licensed under Creative Commons Attribution-ShareAlike 4.0 International.\nhttps://creativecommons.org/licenses/by-sa/4.0/\nFull license: ../../licenses/CC-BY-SA-4.0.txt\n\nDictionary meanings are reference glosses. Readings and meanings can vary by context.\n`,
);
console.log(
  `Generated dictionary for ${characters.size} traditional/simplified characters.`,
);
